// AF_MUSE paid library — mounts onto the existing cashier app.
//
// The pricing shape follows what already works here (ART STUDIO): a buyer has to see the work
// before paying, so browsing and previews are free, and the full text is what costs money.
// A paywall in front of an unseen product sells nothing.
//
//   free   GET /muse                       browse: ids, forms, tags, first line of each piece
//   free   GET /muse/preview/:id           one piece, truncated, with its digest
//   free   GET /muse/manifest.json         the whole catalog, machine-readable
//   paid   GET /muse/piece/:id             the complete piece            $0.02
//   paid   GET /muse/form/:form            every piece in one form       $0.15
//   paid   GET /muse/all                   the entire library            $0.50
//
// Every paid route is registered in the x402 ROUTES table so the 402 challenge is generated by
// the same middleware as the rest of the shop; nothing here re-implements payment.
import fs from "node:fs";
import path from "node:path";

export const MUSE_PRICE = {
  piece: process.env.AF_MUSE_PIECE_PRICE || "$0.02",
  form: process.env.AF_MUSE_FORM_PRICE || "$0.15",
  all: process.env.AF_MUSE_ALL_PRICE || "$0.50",
};

const CANDIDATES = [
  "/workspace/project/AX_MASTER_BRAIN/artifacts/af_muse",
  path.join(process.cwd(), "..", "..", "project", "AX_MASTER_BRAIN", "artifacts", "af_muse"),
];

export function loadMuse() {
  for (const dir of CANDIDATES) {
    const indexPath = path.join(dir, "index.json");
    if (!fs.existsSync(indexPath)) continue;
    try {
      const index = JSON.parse(fs.readFileSync(indexPath, "utf8"));
      const items = [];
      for (const form of Object.keys(index.forms || {})) {
        const f = path.join(dir, `${form}.json`);
        if (!fs.existsSync(f)) continue;
        const data = JSON.parse(fs.readFileSync(f, "utf8"));
        for (const it of data.items || []) items.push(it);
      }
      const byId = new Map(items.map((i) => [i.id, i]));
      return { index, items, byId, dir, loaded: items.length };
    } catch (e) {
      console.warn("[muse] load failed in", dir, e.message);
    }
  }
  return { index: null, items: [], byId: new Map(), dir: null, loaded: 0 };
}

// The preview is the product sample: enough to judge the voice, not enough to use for free.
// For verse, one line. For prose, the first sentence. Always the same rule, so a buyer can
// predict what they get before paying.
export function previewOf(it) {
  if (it.lines) return it.lines.map((l) => (Array.isArray(l) ? l.join("") : l)).slice(0, 1).join("\n");
  if (it.sections) return it.sections[0]?.text?.split("\n").slice(0, 2).join("\n") || "";
  if (it.paragraphs) return it.paragraphs[0].slice(0, 160);
  if (it.scene) return (it.scene.dialogue?.[0]?.line || "").slice(0, 160);
  if (it.text) return it.text.slice(0, 120);
  return "";
}

const strip = (it) => {
  const { _t, ...rest } = it;
  return rest;
};

export function registerMuse(app, { acceptsFor, PUBLIC, demandLog }) {
  const M = loadMuse();
  if (!M.loaded) {
    console.warn("[muse] library not found - paid routes will answer 503");
  } else {
    console.log(`[muse] loaded ${M.loaded} pieces from ${M.dir}`);
  }

  // ---- free: browsing. A 503 here is honest: the shop has no stock loaded. ----
  const need = (_req, res, next) => (M.loaded ? next() : res.status(503).json({
    error: "library not loaded",
    note: "the paid routes would also 503 - do not pay into an empty shop",
  }));

  app.get("/muse", need, (req, res) => {
    const { form, tag, q, limit = "25", offset = "0" } = req.query;
    let rows = M.items;
    if (form) rows = rows.filter((i) => i.form === form);
    if (tag) rows = rows.filter((i) => (i.tags || []).includes(String(tag)));
    if (q) {
      const t = String(q).toLowerCase();
      rows = rows.filter((i) => JSON.stringify(i).toLowerCase().includes(t));
    }
    const off = Math.max(0, Number(offset) || 0);
    const lim = Math.min(Math.max(1, Number(limit) || 25), 100);
    res.json({
      name: M.index?.name, total: rows.length, offset: off, limit: lim,
      forms: M.index?.forms, license: M.index?.license,
      pricing: { preview: "free", piece: MUSE_PRICE.piece, form: MUSE_PRICE.form, all: MUSE_PRICE.all },
      how_to_buy: {
        single: `${PUBLIC}/muse/piece/<id>`,
        one_form: `${PUBLIC}/muse/form/<form>`,
        everything: `${PUBLIC}/muse/all`,
        note: "x402: an unpaid request returns 402 with the price and payTo. No account, no key.",
      },
      items: rows.slice(off, off + lim).map((i) => ({
        id: i.id, form: i.form, title: i.title, tags: i.tags,
        preview: previewOf(i),
        preview_url: `/muse/preview/${i.id}`,
        buy_url: `/muse/piece/${i.id}`,
      })),
    });
  });

  app.get("/muse/manifest.json", need, (_req, res) => {
    res.json({
      name: M.index?.name, version: M.index?.version, license: M.index?.license,
      total: M.loaded, forms: M.index?.forms,
      pricing: { preview: "free", piece: MUSE_PRICE.piece, form: MUSE_PRICE.form, all: MUSE_PRICE.all },
      craft_basis: M.index?.craft_basis,
      signature_note: "Each item carries signature.digest = sha256 over its body. "
        + "Recompute it yourself; the /muse/verify/:id endpoint only restates it.",
      items: M.items.map((i) => ({
        id: i.id, form: i.form, title: i.title, tags: i.tags,
        digest: i.signature?.digest, buy_url: `/muse/piece/${i.id}`,
      })),
    });
  });

  app.get("/muse/preview/:id", need, (req, res) => {
    const it = M.byId.get(req.params.id);
    if (!it) return res.status(404).json({ error: "not found", hint: "browse /muse for ids" });
    res.json({
      id: it.id, form: it.form, title: it.title, tags: it.tags,
      preview: previewOf(it),
      truncated: true,
      digest: it.signature?.digest,
      buy_url: `/muse/piece/${it.id}`,
      price: MUSE_PRICE.piece,
      note: "preview only - the full piece is served by the paid route",
    });
  });

  // Free digest restatement, same idea as /creative/verify: it tells a buyer what to expect,
  // and says plainly that trusting it would defeat the point.
  app.get("/muse/verify/:id", need, (req, res) => {
    const it = M.byId.get(req.params.id);
    if (!it) return res.status(404).json({ error: "not found" });
    res.json({
      id: it.id, algorithm: "sha256", expected: it.signature?.digest,
      how_to_check: "sha256 over json.dumps(item without its signature field, "
        + "sort_keys=True, ensure_ascii=False, separators=(',',':'))",
      signed_by: it.signature?.author,
    });
  });

  // ---- paid handlers. These run only after the x402 middleware has settled. ----
  const paidPiece = (req, res) => {
    const it = M.byId.get(req.params.id);
    if (!it) return res.status(404).json({ error: "not found" });
    if (demandLog) demandLog(req, "paid");
    res.setHeader("X-Author", `${it.signature?.author?.name} <${it.signature?.author?.email}>`);
    res.setHeader("X-Signature", it.signature?.digest || "");
    res.setHeader("X-License", it.license || "");
    res.json(strip(it));
  };

  const paidForm = (req, res) => {
    const form = req.params.form;
    const rows = M.items.filter((i) => i.form === form);
    if (!rows.length) {
      return res.status(404).json({ error: "unknown form", forms: Object.keys(M.index?.forms || {}) });
    }
    if (demandLog) demandLog(req, "paid");
    res.json({
      form, count: rows.length, license: M.index?.license,
      items: rows.map(strip),
    });
  };

  const paidAll = (req, res) => {
    if (demandLog) demandLog(req, "paid");
    const out = {};
    for (const it of M.items) (out[it.form] ||= []).push(strip(it));
    res.json({
      name: M.index?.name, version: M.index?.version, total: M.loaded,
      license: M.index?.license, forms: M.index?.forms, items: out,
    });
  };

  // Route table entries for the x402 middleware. The middleware matches on "METHOD /path"
  // with :params, and generates the 402 challenge from `accepts`.
  const routes = {
    "GET /muse/piece/:id": {
      accepts: acceptsFor(MUSE_PRICE.piece),
      resource: `${PUBLIC}/muse/piece/klon8-01`,
      description: "One complete piece from AF_MUSE (Thai verse, lyrics, screenplay scenes, "
        + "captions, aphorisms, essays). Browse /muse free first; this returns the full text, "
        + "signed with sha256 so you can prove it was not altered.",
      mimeType: "application/json",
      serviceName: "AF_MUSE",
      tags: ["creative", "writing", "thai", "poetry", "lyrics", "screenplay", "content"],
    },
    "GET /muse/form/:form": {
      accepts: acceptsFor(MUSE_PRICE.form),
      resource: `${PUBLIC}/muse/form/haiku`,
      description: "Every piece in one AF_MUSE form (klon8, haiku, song, scene, essay, caption, "
        + "aphorism) in a single call, each with its sha256 signature.",
      mimeType: "application/json",
      serviceName: "AF_MUSE",
      tags: ["creative", "writing", "thai", "bulk", "content"],
    },
    "GET /muse/all": {
      accepts: acceptsFor(MUSE_PRICE.all),
      resource: `${PUBLIC}/muse/all`,
      description: "The whole AF_MUSE library in one call: every form, every piece, signed. "
        + "Cheapest per piece; intended for an agent that wants the full corpus to index.",
      mimeType: "application/json",
      serviceName: "AF_MUSE",
      tags: ["creative", "writing", "thai", "corpus", "bulk", "dataset"],
    },
  };


  // ---- K's free channel -------------------------------------------------------------
  // K owns this library, so K's agents read it without paying. The token sits in the path
  // (same as /k/:token/art/...) so crawlers do not index it; a wrong token is a 404, not a
  // 401, because a 401 would confirm the route is worth guessing at.
  const K_TOKEN = process.env.AF_K_TOKEN || "k-7f3a91c4";
  const kGate = (req, res) => {
    if (req.params.token !== K_TOKEN) {
      res.status(404).json({ error: "not found" });
      return false;
    }
    return true;
  };

  app.get("/k/:token/muse", need, (req, res) => {
    if (!kGate(req, res)) return;
    const { form } = req.query;
    const rows = form ? M.items.filter((i) => i.form === form) : M.items;
    res.json({
      name: M.index?.name, total: rows.length, forms: M.index?.forms,
      license: M.index?.license, owner: "K - free, no payment",
      items: rows.map(strip),
    });
  });

  app.get("/k/:token/muse/:id", need, (req, res) => {
    if (!kGate(req, res)) return;
    const it = M.byId.get(req.params.id);
    if (!it) return res.status(404).json({ error: "not found", hint: "GET /k/<token>/muse for ids" });
    res.setHeader("X-Signature", it.signature?.digest || "");
    res.json(strip(it));
  });

  app.get("/k/:token/muse.json", need, (req, res) => {
    if (!kGate(req, res)) return;
    const out = {};
    for (const it of M.items) (out[it.form] ||= []).push(strip(it));
    res.json({
      name: M.index?.name, version: M.index?.version, total: M.loaded,
      license: M.index?.license, forms: M.index?.forms, items: out,
    });
  });

  return { routes, handlers: { paidPiece, paidForm, paidAll }, M, MUSE_PRICE, K_TOKEN };
}
